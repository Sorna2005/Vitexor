if __name__ == "__main__":

    sample_response = """
## Overall Summary

The implementation is generally good but has a few issues.

## Strengths

- Clean function decomposition
- Good variable names

## Issues

- Missing input validation
- Division by zero is possible

## Security

- No input sanitization

## Performance

- Nested loop can be optimized

## Maintainability

- Duplicate logic detected

## Suggested Improvements

- Add exception handling
- Refactor repeated code

## Final Verdict

Good implementation with minor improvements required.
"""

    parser = ReviewResponseParser()

    review = parser.parse(
        sample_response
    )

    print("=" * 80)
    print("Parser Information")
    print("=" * 80)
    print(parser.info())

    print("\nStatistics")
    print("=" * 80)
    print(
        parser.statistics(review)
    )

    print("\nIs Valid Review?")
    print("=" * 80)
    print(
        parser.validate(review)
    )

    print("\nMarkdown Output")
    print("=" * 80)
    print(
        parser.to_markdown(review)
    )


